"""
Extracts DASHBOARD_HTML from ../bulletspy.py, gzip-compresses it at level 9,
and writes esp32/include/dashboard_html.h as a PROGMEM C byte array.
"""

import gzip
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import bulletspy  # noqa: E402


def main() -> None:
    html_bytes = bulletspy.DASHBOARD_HTML.encode("utf-8")
    gz_bytes = gzip.compress(html_bytes, compresslevel=9)

    out_path = Path(__file__).resolve().parent / "include" / "dashboard_html.h"
    lines = [
        "#pragma once",
        "// SPDX-License-Identifier: PolyForm-Shield-1.0.0",
        "// Copyright (c) 2026 Beanzilla Coffee Worldwide LLC. All rights reserved.",
        "// Required Notice: Copyright (c) 2026 Beanzilla Coffee Worldwide LLC. All rights reserved. Beanzilla, Beanzilla Coffee Worldwide, the Beanzilla Kaiju logo, and BulletSpy are trademarks of Beanzilla Coffee Worldwide LLC.",
        "// Auto-generated by esp32/sync_dashboard.py from bulletspy.py",
        f"// Raw HTML size: {len(html_bytes)} bytes | Gzipped PROGMEM size: {len(gz_bytes)} bytes",
        "#include <stdint.h>",
        "#include <stddef.h>",
        "#ifdef ARDUINO",
        "#include <pgmspace.h>",
        "#else",
        "#define PROGMEM",
        "#endif",
        "",
        f"static constexpr size_t DASHBOARD_HTML_GZ_LEN = {len(gz_bytes)};",
        "static const uint8_t DASHBOARD_HTML_GZ[] PROGMEM = {",
    ]

    for i in range(0, len(gz_bytes), 16):
        chunk = gz_bytes[i : i + 16]
        hex_str = ", ".join(f"0x{b:02x}" for b in chunk)
        lines.append(f"    {hex_str},")

    lines.append("};")
    lines.append("")

    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out_path} ({len(html_bytes)} B -> {len(gz_bytes)} B gzipped)")


if __name__ == "__main__":
    main()
